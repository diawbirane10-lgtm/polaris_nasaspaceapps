def compiled_latex_pdf(tex:str) -> bytes|None:
    """Compile with XeLaTeX where available; never permit shell escape."""
    if not shutil.which('xelatex'):
        return None
    with tempfile.TemporaryDirectory(prefix='polaris_report_') as wd:
        p=Path(wd)
        (p/'report.tex').write_text(tex,encoding='utf-8')
        # Supply the same project insignia to XeLaTeX that ReportLab embeds in PDFs.
        if LOGO_FILE.is_file():
            shutil.copyfile(LOGO_FILE, p / LOGO_NAME)
        try:
            res=subprocess.run(['xelatex','-no-shell-escape','-interaction=nonstopmode',
                                '-halt-on-error','report.tex'],cwd=p,capture_output=True,
                                timeout=35,check=False)
        except (OSError, subprocess.TimeoutExpired):return None
        if res.returncode!=0 or not (p/'report.pdf').exists():
            raise RuntimeError('XeLaTeX compile failed: '+res.stdout.decode('utf-8','replace')[-1300:])
        return (p/'report.pdf').read_bytes()


def make_pdf(data:dict[str,Any],prefer_latex:bool=True)->tuple[bytes,str]:
    """PDF on-demand: exact XeLaTeX where present; portable ReportLab on Vercel."""
    tex=latex_source(data)
    if prefer_latex:
        output=compiled_latex_pdf(tex)
        if output:return output,'XeLaTeX / Libertinus Serif'
    return portable_pdf(data),'ReportLab portable PDF (Libertinus XeLaTeX source separately available)'


