def _tex_escape(s:object)->str:
    # Only plain text can enter LaTeX; never interpolate raw TeX from user input.
    raw=str(s)
    mapping={'\\':r'\textbackslash{}','&':r'\&','%':r'\%','$':r'\$',
             '#':r'\#','_':r'\_','{':r'\{','}':r'\}','~':r'\textasciitilde{}',
             '^':r'\textasciicircum{}'}
    return ''.join(mapping.get(x,x) for x in raw)


def _tex_plot(data:dict[str,Any])->str:
    plots=[]
    for s in data['scenarios']:
        k=s['key']
        values=data['timeseries'][k]
        coords=' '.join('({:.1f},{:.3f})'.format(x['hours_from_start'],x['soc_pct']) for x in values)
        latex_color = {"original":"polarisblue","delayed":"polarisgold","alternative_site_after_delay":"polarisgreen"}[k]
        plots.append(r'\addplot+[no marks,thick,color='+latex_color+r'] coordinates {'+coords+r'};')
        plots.append(r'\addlegendentry{'+_tex_escape(s['label'])+'}')
    return '\n'.join(plots)


